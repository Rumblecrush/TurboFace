local byID
function Trainer:GetClassSpellRankChain(spellID)
    if not byID then
        byID = {}
        local _, class = UnitClass("player")
        for _, chain in ipairs(chainsByClass[class] or {}) do
            for _, id in ipairs(chain) do byID[id] = chain end
        end
    end
    return byID[spellID]
end
